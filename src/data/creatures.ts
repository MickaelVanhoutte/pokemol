/**
 * The last four stencils (Progress rewards, src/data/progress.ts) are the stronger move of an earlier one:
 * every Bestiole that learns the earlier stencil learns them too.
 */
const STENCIL_HEIRS: [heir: string, from: string][] = [
  ['pochoir-21', 'pochoir-15'], // Quake, after Tremor
  ['pochoir-22', 'pochoir-13'], // Stone Blade, after Rockslide
  ['pochoir-23', 'pochoir-02'], // Booming Voice, after Headbonk
  ['pochoir-24', 'pochoir-18'], // Toxic Mud, after Gooey Paste
];
for (const c of CREATURES) for (const [heir, from] of STENCIL_HEIRS) if (c.stencils.includes(from) && !c.stencils.includes(heir)) c.stencils.push(heir);

export const CREATURE_BY_ID: Record<string, SpeciesDef> = Object.fromEntries(CREATURES.map((c) => [c.id, c]));

/**
 * The player's own Bestiole, drawn at the Atelier des Brouillons (src/data/custom.ts): one per game, kept in the
 * save and put among the species when the game loads, never in CREATURES (dex numbers, the Tombola, tests).
 */
export const CUSTOM_ID = '000';
let customArt = '';
let customMini = '';
let customRev = 0;

/** Puts the player's own Bestiole among the species, with its drawing and miniature (or takes it out). */
export function setCustomSpecies(sp?: SpeciesDef, art = '', mini = '') {
  if (sp) CREATURE_BY_ID[CUSTOM_ID] = sp;
  else delete CREATURE_BY_ID[CUSTOM_ID];
  customArt = art;
  customMini = mini;
  customRev++;
}

/** Changes each time the player's own Bestiole is redrawn: the picture caches key on it. */
export const customRevision = () => customRev;
export const customMiniUrl = () => customMini;

/** How many of these ids are Bestiodex species: the player's own Bestiole never completes the Bestiodex. */
export const dexCount = (ids: readonly string[]) => ids.filter((id) => id !== CUSTOM_ID && id in CREATURE_BY_ID).length;

export function creature(id: string): SpeciesDef {
  const c = CREATURE_BY_ID[id];
  if (!c) throw new Error(`Unknown creature ${id}`);
  return c;
}

/** The form a Bestiole of this species has grown into by this level (level evolutions only). */
export function grownForm(id: string, level: number): string {
  const next = creature(id).evolutions?.find((e) => e.level !== undefined && e.level <= level);
  return next ? grownForm(next.to, level) : id;
}

/**
 * Bestiodex number: the position in CREATURES, which is ordered like a GBA dex (evolution lines
 * side by side). Ids stay the keys in saves, maps and card files and never change.
 */
export function dexNo(id: string): string {
  return String(CREATURES.findIndex((c) => c.id === id) + 1).padStart(3, '0');
}

/** A species' type(s): one, or two for dual-type Bestioles. */
export function typesOf(id: string): TypeId[] {
  const c = creature(id);
  return c.type2 ? [c.type, c.type2] : [c.type];
}

/** How a particular creature is called: its nickname, or its species' name. */
export function monLabel(m: { species: string; nickname?: string; egg?: unknown }): string {
  if (m.egg) return tr(L('Œuf', 'Egg'));
  return m.nickname || tr(creature(m.species).name);
}

export const STARTERS = ['001', '002', '003'] as const;

/** Battles mirror a drawing so both Bestioles face each other: ours looks right, the foe looks left. */
export function mirrored(c: SpeciesDef, foe: boolean): boolean {
  return c.faces === (foe ? 'right' : 'left');
}

export function artUrl(c: SpeciesDef): string {
  if (c.id === CUSTOM_ID) return customArt;
  return `${import.meta.env.BASE_URL}cards/${c.id}-${c.slug}.webp`;
}
